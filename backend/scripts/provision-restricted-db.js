#!/usr/bin/env node
'use strict';

/**
 * Build a disposable PostgreSQL database with the two-role architecture the
 * application is meant to run under (Security Hardening Phase 4).
 *
 * The point of this script is that the restricted runtime is not a special
 * test rig: it is the deployment topology described in
 * `scripts/least-privilege.sql`, built here by running that exact file. If the
 * shipped script stops being sufficient, the suite that runs against this
 * database fails.
 *
 *   MIGRATION ROLE   owns the schema, applies migrations, may perform DDL.
 *   RUNTIME ROLE     non-superuser, NOBYPASSRLS, owns nothing, holds only
 *                    SELECT/INSERT/UPDATE/DELETE plus sequence and function
 *                    usage. This is what the tests connect as.
 *
 * ── Usage ────────────────────────────────────────────────────────────────────
 *   node scripts/provision-restricted-db.js --database treniko_rls_test
 *   node scripts/provision-restricted-db.js --database x --through 028
 *   node scripts/provision-restricted-db.js --database x --drop-only
 *
 *   --through N   stop after migration N, leaving the database at that state.
 *                 Used to reproduce the pre-029 production schema so the
 *                 028 -> 029 upgrade can be exercised for real.
 *   --json        print the resulting connection parameters as JSON.
 *
 * ── Safety ───────────────────────────────────────────────────────────────────
 * The script refuses to touch a database whose name does not carry the
 * disposable prefix, so it cannot be pointed at treniko_db by a typo. Roles are
 * created with a random password generated per run; nothing is written to disk
 * and nothing is logged.
 *
 * Admin credentials come from DB_ADMIN_USER / DB_ADMIN_PASSWORD when present,
 * otherwise from the ordinary DB_USER / DB_PASSWORD. Creating roles and
 * databases needs a privileged connection; it is used only for that.
 */

require('dotenv').config();

const crypto = require('crypto');
const path = require('path');
const { spawnSync } = require('child_process');
const { Client } = require('pg');

/** Disposable databases must be named with this prefix. */
const DISPOSABLE_PREFIX = 'treniko_rlstest_';

const MIGRATOR_ROLE = 'treniko_test_migrator';
const APP_ROLE = 'treniko_test_app';

const BACKEND_DIR = path.join(__dirname, '..');
const LEAST_PRIVILEGE_SQL = path.join(__dirname, 'least-privilege.sql');

const adminConfig = () => ({
  host: process.env.DB_HOST || 'localhost',
  port: parseInt(process.env.DB_PORT, 10) || 5432,
  user: process.env.DB_ADMIN_USER || process.env.DB_USER || 'postgres',
  password: process.env.DB_ADMIN_PASSWORD || process.env.DB_PASSWORD || undefined,
  database: 'postgres',
});

const assertDisposable = (database) => {
  if (!database || !database.startsWith(DISPOSABLE_PREFIX)) {
    throw new Error(
      `Refusing to operate on "${database}": disposable databases must be named ${DISPOSABLE_PREFIX}*`
    );
  }
  if (!/^[a-z0-9_]+$/.test(database)) {
    throw new Error(`Refusing to operate on "${database}": unexpected characters in database name`);
  }
};

const withAdmin = async (fn) => {
  const client = new Client(adminConfig());
  await client.connect();
  try {
    return await fn(client);
  } finally {
    await client.end();
  }
};

/** Terminate other sessions so DROP DATABASE cannot be blocked by a stray idle connection. */
const dropDatabase = async (admin, database) => {
  await admin.query(
    `SELECT pg_terminate_backend(pid) FROM pg_stat_activity
      WHERE datname = $1 AND pid <> pg_backend_pid()`,
    [database]
  );
  await admin.query(`DROP DATABASE IF EXISTS "${database}"`);
};

/**
 * Create (or reset the password of) the two roles.
 *
 * Passwords are random per run and returned to the caller in memory only. The
 * role attributes are set explicitly rather than relying on defaults, because
 * these four negatives are the whole point of the runtime role.
 */
const ensureRoles = async (admin) => {
  const passwords = {
    migrator: crypto.randomBytes(24).toString('base64url'),
    app: crypto.randomBytes(24).toString('base64url'),
  };

  for (const [role, password] of [[MIGRATOR_ROLE, passwords.migrator], [APP_ROLE, passwords.app]]) {
    const { rows } = await admin.query('SELECT 1 FROM pg_roles WHERE rolname = $1', [role]);
    if (rows.length === 0) {
      await admin.query(`CREATE ROLE "${role}" LOGIN`);
    }
    // ALTER ROLE ... PASSWORD takes a literal; it cannot be parameterised and
    // a DO block cannot take parameters either. The value is generated by
    // crypto.randomBytes().toString('base64url') so its alphabet is
    // [A-Za-z0-9_-] and it cannot contain a quote — asserted rather than
    // assumed, so a future change of generator cannot turn this into an
    // injection point.
    if (!/^[A-Za-z0-9_-]+$/.test(password)) {
      throw new Error('generated password left the expected alphabet');
    }
    await admin.query(`ALTER ROLE "${role}" LOGIN PASSWORD '${password}'`);
    await admin.query(`ALTER ROLE "${role}" NOSUPERUSER NOBYPASSRLS NOCREATEROLE NOCREATEDB NOREPLICATION`);
  }

  return passwords;
};

/** Run the migration runner as the migration role, in its own process. */
const runMigrations = (database, password, through) => {
  const env = {
    ...process.env,
    DB_HOST: process.env.DB_HOST || 'localhost',
    DB_PORT: String(parseInt(process.env.DB_PORT, 10) || 5432),
    DB_NAME: database,
    DB_USER: MIGRATOR_ROLE,
    DB_PASSWORD: password,
    // Set explicitly, not left to the DB_USER fallback. The migration runner
    // prefers DB_MIGRATION_USER, so an ambient value inherited from the
    // developer's .env would win over DB_USER above and the disposable
    // database's tables would be created by the WRONG role -- leaving the
    // intended migrator unable to grant on them, which is exactly the failure
    // this line prevents.
    DB_MIGRATION_USER: MIGRATOR_ROLE,
    DB_MIGRATION_PASSWORD: password,
    DB_SSL: 'false',
    NODE_ENV: 'test',
  };
  const args = [path.join(__dirname, 'migrate.js'), 'migrate'];
  if (through) args.push('--through', String(through));

  const result = spawnSync(process.execPath, args, {
    cwd: BACKEND_DIR,
    env,
    encoding: 'utf8',
  });
  if (result.status !== 0) {
    throw new Error(
      `Migrations failed for ${database}:\n${result.stdout || ''}\n${result.stderr || ''}`
    );
  }
  return result.stdout;
};

/** Apply the shipped least-privilege script with psql, as the schema owner. */
const applyLeastPrivilege = (database, migratorPassword) => {
  const result = spawnSync(
    'psql',
    [
      '-v', 'ON_ERROR_STOP=1',
      '-v', `app_role=${APP_ROLE}`,
      '-v', `migrator_role=${MIGRATOR_ROLE}`,
      '-h', process.env.DB_HOST || 'localhost',
      '-p', String(parseInt(process.env.DB_PORT, 10) || 5432),
      '-U', MIGRATOR_ROLE,
      '-d', database,
      '-f', LEAST_PRIVILEGE_SQL,
    ],
    { env: { ...process.env, PGPASSWORD: migratorPassword }, encoding: 'utf8' }
  );
  if (result.status !== 0) {
    throw new Error(
      `least-privilege.sql failed on ${database}:\n${result.stdout || ''}\n${result.stderr || ''}`
    );
  }
  return result.stdout;
};

/**
 * Build the database end to end.
 *
 * @param {object} options
 * @param {string} options.database  must start with the disposable prefix
 * @param {string} [options.through] stop after this migration number, e.g. '028'
 * @returns {Promise<{database, appUser, appPassword, migratorUser, migratorPassword, host, port}>}
 */
const provision = async ({ database, through } = {}) => {
  assertDisposable(database);

  const passwords = await withAdmin(async (admin) => {
    const pw = await ensureRoles(admin);
    await dropDatabase(admin, database);
    await admin.query(`CREATE DATABASE "${database}" OWNER "${MIGRATOR_ROLE}"`);
    return pw;
  });

  runMigrations(database, passwords.migrator, through);
  applyLeastPrivilege(database, passwords.migrator);

  return {
    host: process.env.DB_HOST || 'localhost',
    port: parseInt(process.env.DB_PORT, 10) || 5432,
    database,
    appUser: APP_ROLE,
    appPassword: passwords.app,
    migratorUser: MIGRATOR_ROLE,
    migratorPassword: passwords.migrator,
  };
};

/** Apply any migrations that became pending since provisioning (used for 028 -> 029). */
const migrateAgain = (handle) => runMigrations(handle.database, handle.migratorPassword);

const teardown = async (database) => {
  assertDisposable(database);
  await withAdmin((admin) => dropDatabase(admin, database));
};

module.exports = {
  provision,
  migrateAgain,
  teardown,
  runMigrations,
  applyLeastPrivilege,
  DISPOSABLE_PREFIX,
  MIGRATOR_ROLE,
  APP_ROLE,
};

if (require.main === module) {
  const args = process.argv.slice(2);
  const flag = (name) => {
    const i = args.indexOf(`--${name}`);
    return i === -1 ? undefined : args[i + 1];
  };

  const database = flag('database') || `${DISPOSABLE_PREFIX}cli`;
  const run = async () => {
    if (args.includes('--drop-only')) {
      await teardown(database);
      console.log(`dropped ${database}`);
      return;
    }
    const handle = await provision({ database, through: flag('through') });
    if (args.includes('--json')) {
      console.log(JSON.stringify({ ...handle, appPassword: '***', migratorPassword: '***' }, null, 2));
    } else {
      console.log(`provisioned ${handle.database} (runtime role: ${handle.appUser})`);
    }
  };

  run().catch((err) => {
    console.error(err.message);
    process.exit(1);
  });
}
